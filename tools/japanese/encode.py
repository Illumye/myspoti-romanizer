"""How the model is written for the extension: numbers in base 90 over printable ASCII, the kana
of readings and the hiragana of surfaces one character each, everything in one TypeScript module."""

import json

# Printable ASCII minus the record and field separators and what JSON escapes.
DIGITS = "".join(c for c in map(chr, range(0x21, 0x7F)) if c not in ',|"\\')
BASE = len(DIGITS)  # 90
# The katakana of readings (ァ to ヶ, and ー), one digit each.
KANA = "".join(chr(c) for c in range(0x30A1, 0x30F7)) + "ー"
# The hiragana of surfaces, one digit each: most words end in them, and a digit is a third of their UTF-8.
HIRAGANA = "".join(chr(c) for c in range(0x3041, 0x3097)) + "ゝゞ"
assert len(KANA) <= BASE and len(HIRAGANA) <= BASE

_KANA_CODE = {ch: DIGITS[i] for i, ch in enumerate(KANA)}
_HIRAGANA_CODE = {ch: DIGITS[i] for i, ch in enumerate(HIRAGANA)}
# The ASCII digits code hiragana: a number's own digits in a surface (2人) are written fullwidth, as
# the extension spells them when it looks a run up (coded in src/engines/japanese/lexicon.ts).
_NUMBER_DIGIT = {chr(0x30 + d): chr(0xFF10 + d) for d in range(10)}


def number(n: int, width: int) -> str:
    """[n] in [width] digits, clamped to what they can hold."""
    n = max(0, min(BASE**width - 1, n))
    return "".join(DIGITS[n // BASE**p % BASE] for p in reversed(range(width)))


def reading_code(reading: str) -> str | None:
    """A reading in digits, or None when it holds a kana outside KANA."""
    if any(ch not in _KANA_CODE for ch in reading):
        return None
    return "".join(_KANA_CODE[ch] for ch in reading)


# What a form adds to its stem's cost may be less than nothing (a form more common than its class
# is on average): it is written from this many hundredths of a nat below zero.
ENDING_COST_OFFSET = 2000


def conjugations_code(table: list[list[tuple[str, str, int, int]]]) -> str:
    """Each kind's forms, `ending,reading` coded, the class in two digits and the cost in two, `|`
    after each, a space between kinds: neither is a digit."""
    kinds = []
    for rows in table:
        for _, _, _, cost in rows:
            if not 0 <= cost + ENDING_COST_OFFSET < BASE**2:
                raise SystemExit(f"an ending's cost of {cost} does not fit in two digits")
        kinds.append("".join(f"{e},{r}{number(c, 2)}{number(cost + ENDING_COST_OFFSET, 2)}|" for e, r, c, cost in rows))
    return " ".join(kinds)


def surface_code(surface: str) -> str:
    return "".join(_HIRAGANA_CODE.get(ch) or _NUMBER_DIGIT.get(ch, ch) for ch in surface)


def write_model(path: str, model: dict) -> None:
    """The TypeScript module the extension reads (src/engines/japanese/data/model.generated.ts)."""
    size = len(model["flags"])
    lines = [
        "// Generated by tools/japanese/build.py from UniDic 2.1.2 (through MeCab) and corpus statistics: do not edit.",
        "",
        f"/** The digits of every number below, base {BASE}. */",
        f"export const DIGITS = {json.dumps(DIGITS)};",
        "",
        "/** The katakana of the readings, by the digit that codes them. */",
        f"export const KANA = {json.dumps(KANA, ensure_ascii=False)};",
        "",
        "/** The hiragana of the surfaces, by the digit that codes them. */",
        f"export const HIRAGANA = {json.dumps(HIRAGANA, ensure_ascii=False)};",
        "",
        "/** Words by coded surface: `surface,reading`, its class in two digits and cost in one, `|` after each. */",
        f"export const LEXICON = {json.dumps(model['lexicon'], ensure_ascii=False)};",
        "",
        f"export const MAX_SURFACE = {model['max_surface']};",
        "",
        "/** The first characters of the coded surfaces, in the lexicon's order. */",
        f"export const INDEX_CHARS = {json.dumps(model['index_chars'], ensure_ascii=False)};",
        "",
        "/** Where the words of each of them start in LEXICON, three digits each. */",
        f"export const INDEX_STARTS = {json.dumps(model['index_starts'])};",
        "",
        "/** Per class: prefix 1, suffix 2, conjunctive particle 4, conjugating 8, auxiliary 16, desu 32, proper noun 64, numeral 128, counter 256. */",
        f"export const FLAGS: readonly number[] = {json.dumps(model['flags'])};",
        "",
        f"/** Class b after class a, at a * {size} + b, in steps of TRANSITION_STEP; class 0 starts and ends a run. */",
        f"export const TRANSITIONS = {json.dumps(model['transitions'])};",
        "",
        f"export const TRANSITION_STEP = {model['transition_step']};",
        "",
        "/** What one digit of a word's cost is worth, in hundredths of a nat. */",
        f"export const COST_STEP = {model['cost_step']};",
        "",
        "/** Verbs and adjectives by coded stem: `stem,reading`, its kind of conjugation in two digits and cost in one, `|` after each. */",
        f"export const STEMS = {json.dumps(model['stems'], ensure_ascii=False)};",
        "",
        f"export const MAX_STEM = {model['max_stem']};",
        "",
        "/** The first characters of the coded stems, in their order. */",
        f"export const STEM_INDEX_CHARS = {json.dumps(model['stem_index_chars'], ensure_ascii=False)};",
        "",
        "/** Where the stems of each of them start in STEMS, three digits each. */",
        f"export const STEM_INDEX_STARTS = {json.dumps(model['stem_index_starts'])};",
        "",
        "/** Per kind of conjugation, its forms: `ending,reading` coded, the class in two digits and the cost it adds to the stem's in two, from -ENDING_COST_OFFSET, `|` after each, a space between kinds. */",
        f"export const CONJUGATIONS = {json.dumps(model['conjugations'])};",
        "",
        f"export const ENDING_COST_OFFSET = {ENDING_COST_OFFSET};",
        "",
        "/** A run of katakana no word covers: a common noun, at this cost. */",
        f"export const UNKNOWN = {{ cls: {model['unknown_class']}, cost: {model['unknown_cost']} }};",
        "",
        "/** A number in digits: a numeral, at what a numeral costs on average. */",
        f"export const NUMERAL = {{ cls: {model['numeral_class']}, cost: {model['numeral_cost']} }};",
        "",
    ]
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
